#!/usr/bin/env python3
"""
nuscenes_to_npy_single_sweep.py

This script takes the standard nuScenes info files (e.g., nuscenes_infos_val.pkl) 
generated by mmdet3d and converts the associated .bin LiDAR point clouds into 
single-sweep .npy files containing only [X, Y, Z, Intensity] (4 dimensions).

It then outputs a new info file (e.g., nuscenes_infos_val_npy.pkl) where 
`lidar_path` points to the new .npy files and `lidar_sweeps` is emptied.

`lidar_path` in the input pkl must be relative to --data_root (as written by
nuscenes_partial_trainval_infos.py). update_infos_to_v2.py stores bare file
names, which this script does not resolve.

--constant_intensity overwrites the intensity column with a fixed value. The
CARLA training scans have intensity exactly 1.0 everywhere, so zero-shot eval
of the intensity checkpoints uses --constant_intensity 1.0. The .npy files then
go to samples/LIDAR_TOP_NPY_intensity<value> so they never mix with raw ones.

Usage:
  python scripts/offline_preprocessing/nuscenes_to_npy_single_sweep.py \
      --data_root data/nuscenes \
      --info_prefix nuscenes \
      --splits val test

  # zero-shot set from the partial trainval download
  python scripts/offline_preprocessing/nuscenes_to_npy_single_sweep.py \
      --data_root data/nuscenes_zeroshot \
      --splits zeroshot --constant_intensity 1.0
"""

import argparse
import os
import pickle
from pathlib import Path

import numpy as np
from tqdm import tqdm

def process_infos(pkl_path: str, data_root: str, out_dir: str, constant_intensity=None):
    print(f"Loading {pkl_path}...")
    with open(pkl_path, 'rb') as f:
        data = pickle.load(f)

    # Handle mmdet3d v1.1 format
    is_v1_1 = 'metainfo' in data
    data_list = data['data_list'] if is_v1_1 else data['infos']

    npy_subdir = 'LIDAR_TOP_NPY'
    if constant_intensity is not None:
        npy_subdir += f'_intensity{constant_intensity:g}'
    npy_dir = os.path.join(data_root, 'samples', npy_subdir)
    os.makedirs(npy_dir, exist_ok=True)

    # A missing .bin would leave its entry pointing at the 5-feature .bin,
    # which LoadPointsFromNpy(load_dim=4) reads silently wrong. Check first.
    lidar_paths = [info['lidar_points']['lidar_path'] if is_v1_1 else info['lidar_path']
                   for info in data_list]
    missing = [p for p in lidar_paths if not os.path.exists(os.path.join(data_root, p))]
    if missing:
        raise FileNotFoundError(
            f"{len(missing)} of {len(data_list)} lidar files not found under {data_root}, "
            f"e.g. {missing[:3]}")

    print(f"Converting point clouds for {len(data_list)} samples...")
    for info, lidar_path in zip(tqdm(data_list, desc=os.path.basename(pkl_path)), lidar_paths):
        full_lidar_path = os.path.join(data_root, lidar_path)

        # NuScenes standard point clouds are float32 with 5 dims: X, Y, Z, Intensity, Ring_Index
        points = np.fromfile(full_lidar_path, dtype=np.float32)
        points = points.reshape(-1, 5)

        # Slice to 4 dims: [X, Y, Z, Intensity]
        points_4d = np.ascontiguousarray(points[:, :4])
        if constant_intensity is not None:
            points_4d[:, 3] = constant_intensity

        # Save to .npy
        npy_filename = Path(lidar_path).stem + '.npy'
        npy_rel_path = os.path.join('samples', npy_subdir, npy_filename)
        npy_full_path = os.path.join(data_root, npy_rel_path)

        np.save(npy_full_path, points_4d)

        # Update metadata info
        if is_v1_1:
            info['lidar_points']['lidar_path'] = npy_rel_path
            info['lidar_points']['num_pts_feats'] = 4
            info['lidar_sweeps'] = []  # Empty sweeps -> single sweep
        else:
            info['lidar_path'] = npy_rel_path
            info['num_features'] = 4
            info['sweeps'] = []

    if is_v1_1:
        data['metainfo']['point_features'] = (
            'x y z intensity; intensity raw (0-255)' if constant_intensity is None else
            f'x y z intensity; intensity overwritten with constant {constant_intensity:g}')

    out_pkl_name = os.path.basename(pkl_path).replace('.pkl', '_npy.pkl')
    out_pkl = os.path.join(out_dir, out_pkl_name)
    with open(out_pkl, 'wb') as f:
        pickle.dump(data, f, protocol=pickle.HIGHEST_PROTOCOL)

    print(f"Saved NPY-compatible info file to: {out_pkl}\n")


def main():
    parser = argparse.ArgumentParser(description="Convert nuScenes .bin to 4D .npy")
    parser.add_argument('--data_root', type=str, required=True, help="nuScenes dataset root directory")
    parser.add_argument('--info_prefix', type=str, default='nuscenes', help="Prefix of the pkl files (e.g., 'nuscenes')")
    parser.add_argument('--out_dir', type=str, default=None, help="Output directory for the new pkl files. Defaults to data_root.")
    parser.add_argument('--splits', type=str, nargs='+', default=['val', 'test'], help="Which splits to convert")
    parser.add_argument('--constant_intensity', type=float, default=None,
                        help="Overwrite the intensity column with this value (default: keep raw 0-255)")
    args = parser.parse_args()

    if args.out_dir is None:
        args.out_dir = args.data_root

    os.makedirs(args.out_dir, exist_ok=True)

    for split in args.splits:
        pkl_name = f"{args.info_prefix}_infos_{split}.pkl"
        pkl_path = os.path.join(args.data_root, pkl_name)
        if os.path.exists(pkl_path):
            process_infos(pkl_path, args.data_root, args.out_dir, args.constant_intensity)
        else:
            print(f"File {pkl_path} not found. Skipping split '{split}'.")


if __name__ == '__main__':
    main()
